/**
 * The two stemmers are one stemmer.
 *
 * `src/lib/stem.ts` runs in the reader's browser and decides which of their
 * words collide. `scripts/stem.py` in getmcpulse/mcp-schema-study decides the
 * same thing across 4,749 servers, and that answer is the benchmark this page
 * prints a reader's score against. If the two ever disagree about a word, the
 * reader's number and the corpus number stop being the same measurement — and
 * nothing in either repo would say so. The page would just be quietly wrong.
 *
 * So every word both sides must agree on lives in `fixtures/stem.json`,
 * generated by `scripts/04_stem_fixture.py`: Porter's published reference
 * vocabulary, the short acronyms the MIN_STEM_LENGTH deviation exists for, and
 * 13,000 real words sampled from the corpus.
 *
 * Regenerate with `python3 scripts/04_stem_fixture.py` in the study repo and
 * copy the file across. It is committed on both sides so neither test needs a
 * network or the other repo checked out.
 */

import { stem, Surfaces, MIN_STEM_LENGTH } from "../src/lib/stem";
import fixture from "./fixtures/stem.json";

let failures = 0;
let checks = 0;

function eq(label: string, got: unknown, want: unknown) {
  checks++;
  if (JSON.stringify(got) === JSON.stringify(want)) {
    console.log(`pass  ${label}`);
    return;
  }
  failures++;
  console.log(`FAIL  ${label}\n        got  ${JSON.stringify(got)}\n        want ${JSON.stringify(want)}`);
}

const group = (name: string) =>
  console.log(`\n── ${name} ${"─".repeat(Math.max(0, 58 - name.length))}`);

/* ── Parity ───────────────────────────────────────────────────────────────── */
group("every word the Python stemmer produces, this one produces");

eq("fixture declares the deviation this file implements", fixture.min_stem_length, MIN_STEM_LENGTH);

const cases = Object.entries(fixture.cases as Record<string, string>);
const mismatches = cases.filter(([word, expected]) => stem(word) !== expected);

checks++;
if (mismatches.length === 0) {
  console.log(`pass  all ${cases.length} words agree with scripts/stem.py`);
} else {
  failures++;
  console.log(`FAIL  ${mismatches.length} of ${cases.length} words disagree with scripts/stem.py`);
  for (const [word, expected] of mismatches.slice(0, 20)) {
    console.log(`        ${word}: got ${stem(word)}, python says ${expected}`);
  }
}

/* ── The bug this was written for ─────────────────────────────────────────── */
group("the pair that started the correction");

/**
 * Two real tools on one server. They share their one genuinely linking term and
 * the counter scored both of them as distinctive on it, because `screens` and
 * `screening` are different strings.
 *
 *   analyze_job_description  "Extract what a job posting actually screens on."
 *   optimize_resume          "Rewrite a resume so it passes ATS screening."
 */
eq("screens and screening are one word", stem("screens"), stem("screening"));
eq("and that word is screen", stem("screening"), "screen");
eq("screened too", stem("screened"), "screen");

group("the deviation: three-letter acronyms survive");

/**
 * Porter reads the trailing `s` of `ats` as a plural and hands back `at`, which
 * is also a stopword — so the default would delete the most diagnostic noun on
 * the server this whole line of work came from rather than sharpen it.
 */
eq("ats is not at", stem("ats"), "ats");
eq("ids is not id", stem("ids"), "ids");
eq("api is left alone", stem("api"), "api");

/* ── Surfaces ─────────────────────────────────────────────────────────────── */
group("stems are counted, surface words are reported");

const surfaces = new Surfaces();
for (const word of ["screening", "screens", "screened"]) surfaces.add(word);
eq("shortest surface form wins", surfaces.of("screen"), "screens");

const tie = new Surfaces();
tie.add("posts");
tie.add("poste");
eq("alphabetical on a tie", tie.of(stem("posts")), "poste" < "posts" ? "poste" : "posts");

const unseen = new Surfaces();
eq("an unrecorded stem prints as itself", unseen.of("resum"), "resum");

/**
 * Order-independence is what lets the Python side keep one process-wide
 * registry instead of threading one through every function.
 */
const forward = new Surfaces();
const backward = new Surfaces();
const words = ["screening", "screens", "screen", "screened"];
for (const word of words) forward.add(word);
for (const word of [...words].reverse()) backward.add(word);
eq("insertion order does not change the answer", forward.of("screen"), backward.of("screen"));

/* ── Result ───────────────────────────────────────────────────────────────── */
console.log(failures ? `\n${failures} of ${checks} checks FAILED` : `\nall ${checks} checks passed`);
process.exit(failures ? 1 : 0);
